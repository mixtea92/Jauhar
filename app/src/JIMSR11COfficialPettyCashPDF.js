// JIMS R11C — printable one-page A4 Petty Cash PDF, no Excel/handwritten signatures.
// The source is a server-authorized, read-only snapshot (not client-supplied approvers).
import { supabase } from './lib/supabase'
import pdfMake from 'pdfmake/build/pdfmake'
import pdfFonts from 'pdfmake/build/vfs_fonts'

const text = (x, max = 90) => {
  const value = x == null || String(x).trim() === '' ? '—' : String(x).replace(/\s+/g, ' ').trim()
  return value.length > max ? value.slice(0, max - 1) + '…' : value
}
const amount = x => 'RM ' + Number(x || 0).toLocaleString('en-MY', {
  minimumFractionDigits: 2, maximumFractionDigits: 2
})
const date = x => {
  if (!x) return '—'
  const d = new Date(x)
  if (!Number.isNaN(d.valueOf())) {
    return new Intl.DateTimeFormat('en-GB', {
      timeZone: 'Asia/Kuala_Lumpur', day: '2-digit', month: '2-digit', year: 'numeric'
    }).format(d)
  }
  const s = String(x).slice(0, 10)
  return /^\d{4}-\d{2}-\d{2}$/.test(s) ? s.split('-').reverse().join('/') : text(s, 15)
}
const stamp = x => {
  if (!x) return '—'
  const d = new Date(x)
  if (Number.isNaN(d.valueOf())) return text(x, 25)
  return new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Asia/Kuala_Lumpur', day: '2-digit', month: '2-digit', year: 'numeric',
    hour: '2-digit', minute: '2-digit', hour12: false
  }).format(d)
}
const td = (x, bold = false) => ({
  text: text(x, 78), bold, fontSize: 7.2, margin: [0, 3, 0, 3]
})
const rowPair = (label, value) => [
  {text: label, bold: true, color: '#555555', fontSize: 8},
  {text: text(value, 80), fontSize: 8}
]

export function jimsR11CPettyCashDefinition(snapshot) {
  if (snapshot?.document_version !== 'JIMS-R11C-PC-V1' ||
      snapshot?.voucher?.status !== 'closed' ||
      !snapshot.created_by?.account || !snapshot.approved_by?.account) {
    throw new Error('Invalid official closed Petty Cash snapshot.')
  }
  const v = snapshot.voucher
  const f = v.form_data || {}
  const lines = Array.isArray(f.lines) ? f.lines.slice(0, 10) : []
  if (Number(v.total_amount) < 0 || !Number.isFinite(Number(v.total_amount))) {
    throw new Error('Invalid Petty Cash total.')
  }
  const lineTotal = lines.reduce((s, l) => s + Number(l.amount || 0), 0)
  if (Math.abs(lineTotal - Number(v.total_amount)) > 0.011) {
    throw new Error('Petty Cash line total does not match the recorded amount.')
  }
  const tableBody = [
    ['#', 'Receipt Date', 'Reference', 'Purpose / Description', 'Category', 'Amount'].map(x => td(x, true)),
    ...lines.map((l, i) => [
      td(i + 1), td(date(l.receipt_date)), td(text(l.receipt_no, 19)),
      td(text(l.description, 65)), td(text(l.expense_category, 28)),
      td(amount(l.amount))
    ])
  ]
  if (!lines.length) tableBody.push([
    {text:'No expense lines recorded.',colSpan:6,fontSize:8}, {}, {}, {}, {}, {}
  ])
  return {
    pageSize: 'A4',
    pageMargins: [30, 31, 30, 34],
    info: {
      title: 'JAUHAR Official Petty Cash ' + text(v.cv_number, 70),
      author: 'JAUHAR Integrated Management System',
      subject: 'Read-only Petty Cash document — Finance approval'
    },
    defaultStyle: {font:'Roboto',fontSize:9,color:'#252525'},
    styles: {
      brand: {fontSize:15,bold:true,color:'#9e7d38'},
      subtitle: {fontSize:10,bold:true},
      section: {fontSize:9,bold:true,color:'#8e6e31'}
    },
    footer: (page, count) => ({
      columns:[
        {text:'JAUHAR · Generated by JIMS · No handwritten signature required',
          fontSize:7,color:'#777'},
        {text:'Page '+page+' / '+count,fontSize:7,color:'#777',alignment:'right'}
      ],
      margin:[30,0,30,15]
    }),
    content: [
      {text:'JAUHAR MEDICAL CLINIC',style:'brand'},
      {text:'OFFICIAL PETTY CASH VOUCHER',style:'subtitle',margin:[0,3,0,10]},
      {
        table:{widths:['23%','77%'],body:[
          rowPair('Petty Cash No.',v.cv_number),
          rowPair('Status','CLOSED / FINANCE APPROVED'),
          rowPair('Claimant',f.claimant_name),
          rowPair('Staff ID / Position',text(f.staff_id,22)+' / '+text(f.position,38)),
          rowPair('Department / Branch',text(v.applicable_department,40)+' / '+text(f.branch,25)),
          rowPair('Cost Center / Subdept',text(f.charge_cost_center,25)+' / '+text(f.charge_subdepartment,35)),
          rowPair('Claim Category',f.claim_category),
          rowPair('Request / Disbursed',date(f.date_of_request)+' / '+date(f.date_disbursed))
        ]},
        layout:'lightHorizontalLines',margin:[0,0,0,10]
      },
      {text:'EXPENSE DETAILS',style:'section',margin:[0,4,0,5]},
      {
        table:{headerRows:1,widths:[16,65,72,'*',75,71],body:tableBody},
        layout:{
          fillColor:i=>i===0?'#f1ebe0':null,
          hLineColor:'#d7cbbb',vLineColor:'#d7cbbb'
        },
        margin:[0,0,0,8]
      },
      {
        columns:[
          {text:'TOTAL CLAIM',bold:true,fontSize:10,margin:[0,4,0,4]},
          {text:amount(v.total_amount),bold:true,fontSize:11,alignment:'right',
            color:'#80622b',margin:[0,4,0,4]}
        ],margin:[0,4,0,9]
      },
      {text:'REMARKS: '+text(f.remarks,170),fontSize:8,margin:[0,0,0,12]},
      {
        table:{widths:['49%','49%'],body:[
          [
            {stack:[
              {text:'CREATED BY',style:'section',margin:[0,0,0,4]},
              {text:text(snapshot.created_by.account,48),bold:true,fontSize:9},
              {text:text(snapshot.created_by.designation,46),fontSize:8},
              {text:'Date: '+stamp(snapshot.created_by.date),fontSize:8,margin:[0,4,0,0]}
            ],margin:[6,7,6,7]},
            {stack:[
              {text:'APPROVED BY',style:'section',margin:[0,0,0,4]},
              {text:text(snapshot.approved_by.account,48),bold:true,fontSize:9},
              {text:text(snapshot.approved_by.designation,46),fontSize:8},
              {text:'Date: '+stamp(snapshot.approved_by.date),fontSize:8,margin:[0,4,0,0]}
            ],margin:[6,7,6,7]}
          ]
        ]},
        layout:{hLineColor:'#bbab8c',vLineColor:'#bbab8c'},
        margin:[0,0,0,7]
      },
      {text:'System-approved electronic record. The complete audit trail is retained securely in JIMS and is not printed on this form.',
        fontSize:7,color:'#777777'}
    ]
  }
}

export async function downloadOfficialPettyCashPDF(voucher) {
  if (!voucher?.id || voucher.status !== 'closed') {
    throw new Error('Only CLOSED Petty Cash can be downloaded.')
  }
  const {data,error} = await supabase.rpc('jims_r11c_pc_official_snapshot_v1',
    {p_voucher_id:voucher.id})
  if (error) throw error
  if (data?.voucher?.id !== voucher.id) throw new Error('Petty Cash identity mismatch.')
  const definition = jimsR11CPettyCashDefinition(data)
  const vfs = pdfFonts?.pdfMake?.vfs || pdfFonts?.vfs ||
              pdfFonts?.default?.pdfMake?.vfs || pdfFonts?.default?.vfs ||
              pdfFonts?.default || pdfFonts
  if (typeof pdfMake?.createPdf !== 'function' || !vfs || typeof vfs !== 'object') {
    throw new Error('PDF engine unavailable. Refresh the page and try again.')
  }
  if (typeof pdfMake.addVirtualFileSystem === 'function') {
    pdfMake.addVirtualFileSystem(vfs)
  } else {
    pdfMake.vfs = vfs
  }
  const name = String(voucher.cv_number || 'PC').replace(/[^a-z0-9_-]/gi,'_')
  pdfMake.createPdf(definition).download(name+'_Official_Petty_Cash.pdf')
  return {filename: name+'_Official_Petty_Cash.pdf'}
}
